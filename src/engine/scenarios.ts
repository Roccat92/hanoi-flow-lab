/** Split the 4-class scenario mix (shared with SUMO) into the 8 TS vehicle types. */
export function fullMix(mix: readonly number[]): number[] {
  const [m, c, b, t] = mix; const bike = Math.min(0.02, m * 0.5);
  // moto, car, bus, truck, bicycle, taxi, van, SUV
  return [m - bike, c * 0.5, b, t, bike, c * 0.2, c * 0.12, c * 0.18];
}
